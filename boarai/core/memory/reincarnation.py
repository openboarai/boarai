"""
ReincarnationEngine — memory lifecycle management.

Handles the "memory reincarnation" cycle when a session or agent is deleted:
1. Grade entries by value (trash / archive / distill / elevate)
2. Distill high-value entries into compact epitaphs via LLM (with rule-based fallback)
3. Write epitaphs to graveyard/
4. Reincarnate elevated insights to staging area (not directly to global)
5. Self-expire staging entries after 7 days

Also acts as the cold-path Skill Forge:
- Subscribes to PATTERN_RESONANCE events from MemoryWeaver
- Asynchronously distills cross-pod patterns into skill Pods
- Manages skill lifecycle via Reincarnation's built-in grading + expiry

Storage locations:
    .boarai/memory/graveyard/session/{id}.epitaph
    .boarai/memory/graveyard/agent/{name}.epitaph
    .boarai/memory/staging/global_insights.json
"""

import asyncio
import hashlib
import json
import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..event import Event, get_event_bus, publish_event
from .types import MemoryEntry, EntryType, LifecycleState
from .events import (
    MEMORY_INSIGHT_GENERATED, MEMORY_POD_RECYCLED, PATTERN_RESONANCE,
)

# Skill forge distillation prompt
SKILL_FORGE_PROMPT = """You are a skill extractor. From the following multi-context records, extract a reusable problem-solving procedure.

Core Problem: {topic}

Records (from {pod_count} different contexts):
{entries_text}

Output a structured skill document containing:
1. **通用解决步骤** (General Steps) — numbered steps with {{parameter}} placeholders
2. **常见错误与应对** (Common Errors & Solutions)
3. **一句话总结** (One-line summary, ≤ 50 chars)

Format: Markdown. Keep it concise and actionable (< 1500 chars)."""

logger = logging.getLogger(__name__)

# Distillation prompt for LLM
DISTILL_PROMPT = """Please distill the following {count} memory entries into a concise epitaph (max 300 words).

These entries were extracted from a conversation. Summarize:
1. The most important topics discussed
2. Key decisions made
3. User preferences or constraints discovered
4. Any reusable patterns or insights

Also generate semantic expansion tags — synonyms, broader/narrower terms, related concepts.
Mix Chinese AND English. Maximum 15 tags.

Entries:
{entries}

Output a strictly valid JSON with these keys:
- summary (string)
- key_decisions (list of strings)
- key_preferences (list of strings)
- confidence (0.0-1.0 float)
- target_tags (list of strings)
- semantic_tags (list of strings, max 15, Chinese+English mixed)"""

# Rule-based fallback template
RULE_FALLBACK_TEMPLATE = """## Rule-based Epitaph (LLM unavailable)

Top entries from this session:

{entries_text}

*This epitaph was generated by rule-based fallback preserving the top-3 most important entries.*"""


class ReincarnationEngine:
    """Handles the memory reincarnation cycle."""

    def __init__(self, manager=None):
        self._manager = manager

    def set_manager(self, manager) -> None:
        self._manager = manager

    def grade_entries(self, entries: List[MemoryEntry]) -> Dict[str, List[MemoryEntry]]:
        """Grade entries by value for lifecycle treatment."""
        graded: Dict[str, List[MemoryEntry]] = {
            "trash": [],
            "archive": [],
            "distill": [],
            "elevate": [],
        }

        for e in entries:
            if e.lifecycle_state != LifecycleState.ACTIVE.value:
                graded["trash"].append(e)
                continue

            imp = e.importance
            etype = e.entry_type
            tags = e.tags or []
            insight = getattr(e, 'insight_level', 0)

            # Auto-extracted Q&A with insight_level=0 → trash (memory pollution)
            if (etype == EntryType.FACT.value
                    and "auto_extracted" in tags
                    and insight <= 0
                    and imp < 0.7):
                graded["trash"].append(e)
                continue

            # Importance < 0.3 → trash (regardless of type)
            if imp < 0.3:
                graded["trash"].append(e)
            # Importance 0.3-0.7 → archive
            elif imp < 0.7:
                graded["archive"].append(e)
            # Importance >= 0.7, fact/decision → distill
            elif etype in (EntryType.FACT.value, EntryType.DECISION.value, EntryType.PATTERN.value):
                if imp >= 0.85 and etype in (EntryType.DECISION.value, EntryType.INSIGHT.value):
                    graded["elevate"].append(e)
                else:
                    graded["distill"].append(e)
            # Importance >= 0.7, other types → archive
            else:
                graded["archive"].append(e)

        return graded

    async def distill_to_epitaph(
        self,
        entries: List[MemoryEntry],
        llm_service=None,
    ) -> tuple:
        """Distill entries into an epitaph with semantic tags."""
        if not entries:
            return (None, [])

        # Primary: LLM distillation
        if llm_service:
            try:
                entries_json = json.dumps(
                    [{"topic": e.topic, "content": e.content[:300],
                      "type": e.entry_type, "importance": e.importance}
                     for e in entries[:50]],
                    ensure_ascii=False,
                )
                prompt = DISTILL_PROMPT.format(count=len(entries), entries=entries_json)

                response = await llm_service.chat(
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.3,
                    max_tokens=500,
                )
                # Ledger the distillation call — it bypasses the run executor
                # and would otherwise be invisible to token statistics.
                try:
                    from boarai.core.session.usage_ledger import get_usage_ledger

                    await get_usage_ledger().record_side_usage(
                        getattr(response, "usage", None) or {},
                        kind="distill",
                        model=getattr(response, "model", None) or "unknown",
                        agent_name="distill_worker",
                    )
                except Exception:  # noqa: BLE001
                    pass
                if response and response.content and response.content.strip():
                    epitaph = response.content.strip()
                    tags = []
                    # Try to extract JSON if LLM returned it
                    try:
                        data = json.loads(epitaph)
                        parts = []
                        if data.get("summary"):
                            parts.append(data["summary"])
                        if data.get("key_decisions"):
                            parts.append("关键决策: " + ", ".join(data["key_decisions"][:5]))
                        if data.get("key_preferences"):
                            parts.append("偏好: " + ", ".join(data["key_preferences"][:5]))
                        if parts:
                            epitaph = "\n".join(parts)
                        # Extract semantic tags
                        tags = list(data.get("semantic_tags", []))[:15]
                        # Also include target_tags as indexable
                        extra = list(data.get("target_tags", []))[:5]
                        for t in extra:
                            if t not in tags:
                                tags.append(t)
                    except (json.JSONDecodeError, TypeError):
                        pass
                    return (epitaph, tags)
            except Exception as e:
                logger.warning(f"LLM distillation failed, using fallback: {e}")

        # Fallback: rule-based top-3 (no semantic tags)
        top = sorted(entries, key=lambda e: e.importance, reverse=True)[:3]
        lines = []
        for i, e in enumerate(top, 1):
            content_preview = e.content[:200]
            if len(e.content) > 200:
                content_preview += "..."
            lines.append(f"[Entry {i}] ({e.entry_type}) {e.topic}: {content_preview}")

        fallback_epitaph = RULE_FALLBACK_TEMPLATE.format(entries_text="\n\n".join(lines))
        return (fallback_epitaph, [])

    async def write_epitaph(
        self,
        pod_uri: str,
        epitaph: str,
        metadata: Optional[Dict] = None,
    ) -> str:
        """Write epitaph to graveyard."""
        if not self._manager:
            return ""

        # Determine graveyard path
        if pod_uri.startswith("pod://session/"):
            sid = pod_uri[len("pod://session/"):]
            graveyard_dir = self._manager.pod_store.boarai_dir / "memory" / "graveyard" / "session"
        elif pod_uri.startswith("pod://agent/"):
            name = pod_uri[len("pod://agent/"):]
            graveyard_dir = self._manager.pod_store.boarai_dir / "memory" / "graveyard" / "agent"
        else:
            graveyard_dir = self._manager.pod_store.boarai_dir / "memory" / "graveyard"

        graveyard_dir.mkdir(parents=True, exist_ok=True)

        # Write epitaph
        filepath = graveyard_dir / f"{Path(pod_uri).name}.epitaph"
        epitaph_data = {
            "pod_uri": pod_uri,
            "epitaph": epitaph,
            "created_at": datetime.now().isoformat(),
            "metadata": metadata or {},
        }
        import aiofiles
        async with aiofiles.open(filepath, "w", encoding="utf-8") as f:
            await f.write(json.dumps(epitaph_data, ensure_ascii=False, indent=2))

        logger.info(f"Epitaph written to {filepath}")
        return str(filepath)

    async def reincarnate_to_staging(
        self,
        epitaph: str,
        source_pod: str,
        tags: List[str],
        entries: List[MemoryEntry],
    ) -> int:
        """Reincarnate epitaph to staging area (NOT directly to global)."""
        if not self._manager or not epitaph:
            return 0

        staging_path = self._manager.pod_store.boarai_dir / "memory" / "staging" / "global_insights.json"
        staging_path.parent.mkdir(parents=True, exist_ok=True)

        # Determine target(s) from tags
        targets = set()
        types_involved = set(e.entry_type for e in entries)
        has_decision = EntryType.DECISION.value in types_involved
        has_insight = EntryType.INSIGHT.value in types_involved

        if "personal" in tags or "preference" in tags:
            targets.add("pod://agent/{default}")
        if any(t in tags for t in ("architecture", "design", "system", "decision")):
            targets.add("pod://global")
        if any(t in tags for t in ("bug", "vulnerability", "security")):
            targets.add("pod://global")  # Auto-approve security insights
        if has_insight:
            targets.add("pod://global")
        if not targets:
            targets.add("pod://global")  # Default target

        # Calculate confidence (simple heuristic: based on importance of entries).
        # NOTE: no hard 0.95 cap here — high-value distillations (e.g. decisions
        # from important entries) must be able to exceed the auto-confirm
        # threshold (> 0.95) so the global memory can form automatically.
        avg_importance = sum(e.importance for e in entries) / max(len(entries), 1)
        confidence = min(0.98, avg_importance * (1.15 if has_decision else 1.05))

        # Create staging entry
        staging_entry = {
            "id": f"stg_{datetime.now().strftime('%Y%m%d%H%M%S')}",
            "source_pod": source_pod,
            "epitaph": epitaph,
            "targets": list(targets),
            "confidence": confidence,
            "tags": tags,
            "created_at": datetime.now().isoformat(),
            "expires_at": (datetime.now() + timedelta(days=7)).isoformat(),
            "status": "confirmed" if confidence > 0.95 else "pending",
        }

        # Read existing staging
        import aiofiles
        existing = {"insights": []}
        if staging_path.exists():
            try:
                async with aiofiles.open(staging_path, "r", encoding="utf-8") as f:
                    content = await f.read()
                if content.strip():
                    existing = json.loads(content)
            except Exception:
                pass

        existing.setdefault("insights", []).append(staging_entry)

        # Write back
        async with aiofiles.open(staging_path, "w", encoding="utf-8") as f:
            await f.write(json.dumps(existing, ensure_ascii=False, indent=2))

        # If auto-confirmed (confidence > 0.95), merge to global immediately
        count = 1
        if staging_entry["status"] == "confirmed":
            await self._merge_to_global(staging_entry)

        logger.info(f"Reincarnated {count} insights to staging for {source_pod}")
        return count

    async def _merge_to_global(self, staging_entry: Dict) -> bool:
        """Merge a confirmed staging entry into pod://global."""
        if not self._manager:
            return False

        entry = MemoryEntry(
            pod_uri="pod://global",
            topic=f"[Reincarnated] {staging_entry.get('tags', ['insight'])[:3]}",
            content=staging_entry.get("epitaph", ""),
            entry_type=EntryType.INSIGHT.value,
            tags=staging_entry.get("tags", []),
            importance=0.85,
            insight_level=1,
            metadata={
                "reincarnated_from": staging_entry.get("source_pod"),
                "reincarnation_time": datetime.now().isoformat(),
            },
        )
        await self._manager.remember("pod://global", entry, publish=True)
        return True

    async def confirm_staging(self, entry_id: str, approve: bool = True) -> bool:
        """Manually confirm or reject a staging insight."""
        if not self._manager:
            return False

        staging_path = self._manager.pod_store.boarai_dir / "memory" / "staging" / "global_insights.json"
        if not staging_path.exists():
            return False

        import aiofiles
        async with aiofiles.open(staging_path, "r", encoding="utf-8") as f:
            content = await f.read()
        if not content.strip():
            return False

        data = json.loads(content)
        insights = data.get("insights", [])
        modified = False

        for insight in insights:
            if insight.get("id") == entry_id:
                if approve:
                    insight["status"] = "confirmed"
                    await self._merge_to_global(insight)
                else:
                    insight["status"] = "rejected"
                modified = True
                break

        if modified:
            async with aiofiles.open(staging_path, "w", encoding="utf-8") as f:
                await f.write(json.dumps(data, ensure_ascii=False, indent=2))

        return modified

    async def expire_staging(self) -> int:
        """Remove all expired staging entries (older than 7 days)."""
        if not self._manager:
            return 0

        staging_path = self._manager.pod_store.boarai_dir / "memory" / "staging" / "global_insights.json"
        if not staging_path.exists():
            return 0

        import aiofiles
        async with aiofiles.open(staging_path, "r", encoding="utf-8") as f:
            content = await f.read()
        if not content.strip():
            return 0

        data = json.loads(content)
        insights = data.get("insights", [])
        now = datetime.now()
        alive = []
        expired_count = 0

        for insight in insights:
            expires = insight.get("expires_at")
            if expires:
                try:
                    if datetime.fromisoformat(expires) <= now:
                        expired_count += 1
                        continue
                except Exception:
                    pass
            alive.append(insight)

        if expired_count > 0:
            data["insights"] = alive
            async with aiofiles.open(staging_path, "w", encoding="utf-8") as f:
                await f.write(json.dumps(data, ensure_ascii=False, indent=2))
            logger.info(f"Expired {expired_count} staging insights")

        return expired_count

    # ==================== Skill Forge (Pattern Resonance) ====================

    async def forge_skill(self, payload: Dict[str, Any]) -> Optional[str]:
        """Dark-matter forge: distill cross-pod resonance into a skill Pod."""
        topic = payload.get("topic", "")
        sample_dicts = payload.get("sample_entries", [])
        source_pods = payload.get("source_pods", [])
        agent = payload.get("agent", "default")

        if not topic or not sample_dicts:
            return None

        sample_entries = [MemoryEntry.from_dict(e) for e in sample_dicts]
        logger.info(f"[Forge] 锻造开始: topic={topic}, pods={len(source_pods)}, entries={len(sample_entries)}")

        # Step 1: Distill raw entries into skill content
        skill_content = await self._distill_to_skill(topic, sample_entries, source_pods)
        if not skill_content:
            logger.warning(f"[Forge] 蒸馏失败，跳过: {topic}")
            return None

        # Step 2: Write to skill Pod
        skill_hash = hashlib.sha256(topic.encode()).hexdigest()[:8]
        skill_pod = f"pod://skill/forge_{skill_hash}"

        await self._manager.remember(
            skill_pod,
            MemoryEntry(
                topic=topic,
                content=skill_content,
                entry_type=EntryType.PROCEDURE.value,
                tags=["auto_skill", *self._extract_tags(topic)],
                importance=0.9,
                metadata={
                    "skill_hash": skill_hash,
                    "source_pods": source_pods,
                    "agent": agent,
                    "forged_at": datetime.now().isoformat(),
                },
            ),
        )

        # Step 3: Mount to global (public muscle memory, never decays)
        await self._manager.create_synapse(
            source_pod_uri=skill_pod,
            target_context="pod://global",
            label=f"auto_skill:{skill_hash}",
            weight=0.9,
            decay_rate=0.0,  # Never decays — shared common knowledge
        )

        # Step 4: Mount to current agent (per-turn decay)
        await self._manager.create_synapse(
            source_pod_uri=skill_pod,
            target_context=f"pod://agent/{agent}",
            label=f"auto_skill:{skill_hash}",
            weight=0.8,
            decay_rate=0.05,  # Decays ~50 turns
        )

        # Step 5: Attenuate source entry weights (prevent re-triggering)
        for entry in sample_entries:
            await self._manager.update_entry_importance(
                entry.entry_id, entry.importance * 0.9,
            )

        logger.info(f"[Forge] 锻造完成: {skill_pod} ({topic})")
        return skill_pod

    async def _distill_to_skill(
        self,
        topic: str,
        entries: List[MemoryEntry],
        source_pods: List[str],
    ) -> Optional[str]:
        """Distill raw entries into structured skill content."""
        if not entries:
            return None

        llm_service = getattr(self._manager, '_llm_service', None)

        # Primary: LLM distillation
        if llm_service:
            try:
                entries_text = "\n\n".join(
                    f"[Context: {e.pod_uri}]\nTopic: {e.topic}\n{e.content[:500]}"
                    for e in entries
                )
                prompt = SKILL_FORGE_PROMPT.format(
                    topic=topic,
                    pod_count=len(source_pods),
                    entries_text=entries_text,
                )

                response = await llm_service.chat(
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.3,
                    max_tokens=600,
                )
                try:
                    from boarai.core.session.usage_ledger import get_usage_ledger

                    await get_usage_ledger().record_side_usage(
                        getattr(response, "usage", None) or {},
                        kind="skill_forge",
                        model=getattr(response, "model", None) or "unknown",
                        agent_name="skill_forge",
                    )
                except Exception:  # noqa: BLE001
                    pass
                if response and getattr(response, 'content', None):
                    content = response.content.strip()
                    if len(content) > 50:  # Sanity check: must be substantial
                        return content[:2000]
            except Exception as e:
                logger.warning(f"[Forge] LLM 蒸馏失败，使用回退: {e}")

        # Fallback: rule-based top-3 concatenation
        top = sorted(entries, key=lambda e: e.importance, reverse=True)[:3]
        parts = [f"# {topic}\n"]
        for i, e in enumerate(top, 1):
            parts.append(f"## 方法 {i} (来自 {e.pod_uri})\n{e.content[:300]}")
        return "\n\n".join(parts) if len(parts) > 1 else None

    def _extract_tags(self, topic: str) -> List[str]:
        """Extract simple tags from a topic string."""
        import re
        # Split by common delimiters, take meaningful words
        words = re.split(r'[\s,;:()/\\\-_]+', topic.lower())
        return [w for w in words if len(w) > 2 and w not in (
            'the', 'and', 'for', 'with', 'from', 'that', 'this',
        )][:5]
